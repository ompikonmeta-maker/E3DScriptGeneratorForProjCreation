/* .mac files and README text. Formats: docs/OUTPUT-FORMAT.md. Command lines must stay identical
   to tools/reference_generator.py; comment lines are free text but kept identical too. */
(function (E) {
  'use strict';

  const header = (title, notes) => {
    const bar = '$* ' + '='.repeat(59);
    return [bar, `$* ${title}`, ...notes.map(n => `$* ${n}`), bar, '$*'];
  };
  E.eol = cfg => ((cfg.d.project || {}).lineEnding === 'LF' ? '\n' : '\r\n');
  const join = (lines, eol) => lines.join(eol) + eol;
  const NEW_ZONE_WARNING = 'WARNING: NEW ZONE after navigating to a site is not yet tested (facts sec 9).';

  // Run order (README, screen 6, register "Setup Steps"). ASCII only: it is written into README.
  E.RUN_ORDER = [
    ['P', 'Delete old DBs, MDB empty, nobody logged in', '-', 'Admin', 'Databases list'],
    ['0', 'New teams', '00-TEAMS', 'Admin', 'Team count'],
    ['B1', 'CREATE DB + ADD to MDB', 'per row', 'Admin', 'DBNO, MDB positions'],
    ['-', 'Re-enter DESIGN', '-', 'Design', 'New DBs visible'],
    ['B2', 'Separators + sites in display order', 'per row', 'Design', 'Model Explorer = Site Order'],
    ['B3', 'Zones', 'per row', 'Design', 'Zone count'],
    ['R', 'Repeat B1-B3 per row, in order', '-', '-', '-'],
    ['90', 'Reference DBs to MDB', '90-REFERENCE', 'Admin', 'MDB member count'],
    ['99', 'Fix MDB order (optional)', '99-FIXUP', 'Admin', 'Only if wrong'],
  ];
  E.KNOWN_ISSUE = [
    "Random '(43,41) Unable to open DB ... MCD:6 The handle is invalid' while creating DBs.",
    'Note the DB, delete it in Admin if broken, recreate it, continue.',
  ];

  function siteLines(dd, state) {
    const L = [];
    for (const s of E.siteOrder(dd)) {
      L.push(`NEW SITE ${s.name}` + (s.db !== state.lastDb ? ` DB ${s.db}` : ''));
      state.lastDb = s.db;
    }
    return L;
  }
  const zoneLines = dd => {
    const L = [];
    for (const c of dd.cells) if (c.zones.length) { L.push(c.site); for (const z of c.zones) L.push(`NEW ZONE ${z}`); }
    return L;
  };
  const createLines = (cfg, dd) => {
    const def = cfg.d.dbDefaults || {};
    return dd.cells.map(c => `CREATE DB ${c.db} ${def.type} ACCESS ${def.access} CLAIM ${def.claim} DBNO ${c.dbno} DESC '${c.desc}'`);
  };
  const addLines = dd => [`SET MDB ${dd.mdb}`, ...dd.cells.map(c => `ADD ${c.db} ${c.pos}`)];

  // Returns an ordered list of {path, folder, name, text, module, step, content}.
  E.generate = function (cfg, model) {
    const d = cfg.d, t = d.templates || {}, p = d.project || {}, out = d.output || {};
    const eol = E.eol(cfg), comb = d.combination || {};
    const pctx = {};
    const gen = `Generated by E3D Setup Generator - ${p.code} - ${p.target}`;
    const files = [];
    const add = (folder, name, lines, module, step, content) => {
      files.push({ path: folder ? `${folder}/${name}` : name, folder: folder || '', name, text: join(lines, eol), module, step, content });
    };

    // 00-TEAMS
    const teamAttr = cfg.role('team')[0];
    const teams = teamAttr ? teamAttr.rows || [] : [];
    const newTeams = teams.filter(r => !r.existing), oldTeams = teams.filter(r => r.existing);
    let L = header(`${p.code} - STEP 0 - TEAMS - ADMIN`, [gen, 'Run once, before the first discipline.']);
    L.push(`$* --- ${newTeams.length} new teams ---`);
    for (const r of newTeams) L.push(`CREATE TEAM ${r.kode} DESC '${r.desc}'`);
    for (const r of newTeams) if ((r.anggota || []).length) { L.push(`SET TEAM ${r.kode}`); for (const u of r.anggota) L.push(`TADD ${u}`); }
    if (out.includeExistingTeamsBlock && oldTeams.length) {
      L.push('$*', '$* --- existing teams: only if they were deleted (normally keep) ---');
      for (const r of oldTeams) L.push(`$* CREATE TEAM ${r.kode} DESC '${r.desc}'`);
      for (const r of oldTeams) if ((r.anggota || []).length) { L.push(`$* SET TEAM ${r.kode}`); for (const u of r.anggota) L.push(`$* TADD ${u}`); }
    }
    add(E.render(cfg, t.teamsFolder, pctx), E.render(cfg, t.teamsFile, pctx), L, 'Admin', '0', `${newTeams.length} CREATE TEAM`);

    if (out.split === 'perStep') {
      const pre = p.filePrefix || '';
      const all = model.disciplines, nDb = model.cells.length;
      L = header(`ALL ROWS - STEP B1 - ADMIN: CREATE ${nDb} DB + MDB`,
        [gen, 'Team must exist (00-TEAMS). If a CREATE line fails: recreate that DB, continue.', 'Rows in order; each block has its own SET MDB.']);
      for (const dd of all) L.push(`$* --- ${dd.row.desc} ---`, ...createLines(cfg, dd), '$*', ...addLines(dd));
      add('B1', `${pre}B1-CREATE-DB-MDB-ADMIN.mac`, L, 'Admin', 'B1', `${nDb} CREATE DB + ADD`);
      L = header(`ALL ROWS - STEP B2 - DESIGN: separators + ${nDb} sites (display order)`,
        [gen, 'DB given once per DB (first site); next lines without DB go to the same DB.', 'Re-enter DESIGN after B1.']);
      const st = { lastDb: null };
      for (const dd of all) L.push(`$* --- ${dd.row.desc} ---`, ...siteLines(dd, st));
      L.push('$*', 'SAVEWORK');
      add('B2', `${pre}B2-SITES-DESIGN.mac`, L, 'Design', 'B2', `${nDb} sites + separators`);
      const withZones = all.filter(dd => dd.cells.some(c => c.zones.length));
      if (withZones.length) {
        L = header('ALL ROWS - STEP B3 - DESIGN: zones',
          [gen, ...(E.FACTS.newZoneTested ? [] : [NEW_ZONE_WARNING]), 'Each block: go to SITE, NEW ZONE.']);
        for (const dd of withZones) L.push(`$* --- ${dd.row.desc} ---`, ...zoneLines(dd));
        L.push('$*', 'SAVEWORK');
        add('B3', `${pre}B3-ZONES-DESIGN.mac`, L, 'Design', 'B3', 'zones');
      }
    } else {
      for (const dd of model.disciplines) {
        const ctx = dd.ctx, cells = dd.cells, name = String(dd.row.desc).toUpperCase();
        const folder = t.discFolder ? E.render(cfg, t.discFolder, ctx) : '';
        const range = `${cells[0].pos}-${cells[cells.length - 1].pos}`;
        L = header(`${name} (${cells[0].team}) - STEP B1 - ADMIN: CREATE ${cells.length} DB + MDB`,
          [gen, 'Team must exist (00-TEAMS). If a CREATE line fails: recreate that DB, continue.', `MDB positions ${range}.`]);
        L.push(...createLines(cfg, dd), '$*', ...addLines(dd));
        add(folder, E.render(cfg, t.b1File, ctx), L, 'Admin', 'B1', `${cells.length} CREATE DB + ADD`);

        L = header(`${name} - STEP B2 - DESIGN: separators + ${cells.length} sites (display order)`,
          [gen, 'DB given once per DB (first site); next lines without DB go to the same DB.', 'Re-enter DESIGN after B1.']);
        L.push(...siteLines(dd, { lastDb: null }), '$*', 'SAVEWORK');
        const nSep = (dd.sepDiscipline ? 1 : 0) + dd.groupSeps.size;
        add(folder, E.render(cfg, t.b2File, ctx), L, 'Design', 'B2', `${nSep} separators + ${cells.length} sites`);

        if (cells.some(c => c.zones.length)) {
          L = header(`${name} - STEP B3 - DESIGN: zones`,
            [gen, ...(E.FACTS.newZoneTested ? [] : [NEW_ZONE_WARNING]), 'Each block: go to SITE, NEW ZONE.']);
          L.push(...zoneLines(dd), '$*', 'SAVEWORK');
          const nz = cells.reduce((n, c) => n + c.zones.length, 0);
          add(folder, E.render(cfg, t.b3File, ctx), L, 'Design', 'B3', `${nz} zones`);
        }
      }
    }

    const refs = d.referenceDbs || [];
    if (out.includeReference && refs.length) {
      L = header('REFERENCE DBs - ADMIN: add to MDB', [gen, 'Run AFTER all disciplines.']);
      L.push(`SET MDB ${comb.mdb}`);
      for (const r of refs) L.push(r.active ? `ADD ${r.db} ${r.pos}` : `$* ADD ${r.db}   <- ${r.note || ''}`);
      add(E.render(cfg, t.refFolder, pctx), E.render(cfg, t.refFile, pctx), L, 'Admin', '90', `${refs.filter(r => r.active).length} ADD`);
    }

    if (out.includeFixup) {
      L = header('MDB FIX-UP - ADMIN: CURRENT db n for all (final order)',
        [gen, 'Use only if the MDB order is wrong.', 'A DB that is not in the MDB stops the macro: ADD it first.']);
      const mdbs = [...new Set([...model.cells.map(c => c.mdb), comb.mdb])];
      for (const m of mdbs) {
        const cells = model.cells.filter(c => c.mdb === m);
        const rs = m === comb.mdb ? refs.filter(r => r.active) : [];
        if (!cells.length && !rs.length) continue;
        L.push(`SET MDB ${m}`, ...cells.map(c => `CURRENT ${c.db} ${c.pos}`), ...rs.map(r => `CURRENT ${r.db} ${r.pos}`));
      }
      add(E.render(cfg, t.fixupFolder, pctx), E.render(cfg, t.fixupFile, pctx), L, 'Admin', '99', 'CURRENT all DBs');
    }
    return files;
  };

  // Every path in the ZIP, in package order (OUTPUT-FORMAT §1).
  E.packageNames = function (cfg, files) {
    const o = cfg.d.output || {}, names = [];
    if (o.includeReadme) names.push('00-README.txt');
    names.push(...files.map(f => f.path));
    if (o.includeRegister) names.push(E.render(cfg, (cfg.d.templates || {}).registerFile, {}));
    if (o.includeConfig) names.push('config.json');
    return names;
  };

  const pad2 = n => String(n).padStart(2, '0');
  E.stamp = date => `${date.getFullYear()}-${pad2(date.getMonth() + 1)}-${pad2(date.getDate())} ${pad2(date.getHours())}:${pad2(date.getMinutes())}`;

  E.readme = function (cfg, model, issues, files, date) {
    const p = cfg.d.project || {}, c = E.counts(cfg, model);
    const folders = [...new Set(files.filter(f => /^B[123]$/.test(f.step)).map(f => f.folder))];
    const warn = [];
    if (c.zones && !E.FACTS.newZoneTested) warn.push('B3: NEW ZONE after navigating to a site is not yet tested (facts sec 9).');
    const seen = new Set();
    for (const i of issues.filter(i => i.severity === 'warning' && i.id !== 'V19')) {
      const m = `${i.message} [${i.id}${i.ref && i.ref !== '-' ? ' ' + i.ref.replace('§', 'sec ') : ''}]`;
      if (!seen.has(m)) { seen.add(m); warn.push(m); }
    }
    const shown = warn.slice(0, 40);
    if (warn.length > shown.length) shown.push(`... ${warn.length - shown.length} more (see register sheet Validation)`);
    const widths = [4, 44, 14, 7];
    const row = r => ' ' + r.map((v, i) => (i < widths.length ? String(v).padEnd(widths[i]) : v)).join(' ').trimEnd();
    const L = [
      `${p.code} (${p.name}) - E3D SETUP PACKAGE`,
      `Generated ${E.stamp(date)} by E3D Setup Generator. Target: ${p.target}.`,
      '',
      'PREPARATION (Admin, SYSTEM)',
      ' - Delete old DBs of this setup if re-running. Check the MDB is empty and no old DB files remain.',
      ' - Nobody else logged in to the project.',
      '',
      'STEPS (command macros only)',
      ' 00-TEAMS -> per row: B1 (Admin) -> re-enter DESIGN -> B2 sites (Design) -> B3 zones (Design)',
      ` Rows in order: ${folders.join(', ')}`,
      ' Then 90-REFERENCE (Admin). 99-FIXUP only if the MDB order is wrong.',
      '',
      'RUN ORDER',
      row(['Step', 'What', 'File', 'Module', 'Check']),
      ...E.RUN_ORDER.map(row),
      '',
      'WARNINGS',
      ...(shown.length ? shown.map(w => ` - ${w}`) : [' - none']),
      '',
      'KNOWN ISSUE',
      ...E.KNOWN_ISSUE.map(s => ' ' + s),
      '',
      'COUNTS',
      ` Teams new/existing: ${c.teamsNew}/${c.teamsExisting}  DBs: ${c.dbs}  Sites: ${c.sites}  Separators: ${c.separators}  Zones: ${c.zones}  Reference DBs: ${c.refsActive}`,
    ];
    return join(L.map(s => s.replace(/[^\x00-\x7F]/g, '?')), E.eol(cfg));
  };
})(E3D);
